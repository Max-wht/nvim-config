local function copy_icon(icon)
  return { glyph = icon.glyph, hl = icon.hl }
end

local function resolve_icon(mini_icons, spec)
  local preferred = icon_overrides[spec.id] or source_icons[spec.id]
  if preferred then
    return copy_icon(preferred)
  end

  for _, name in ipairs(spec.files or {}) do
    local glyph, hl, is_default = mini_icons.get("file", name)
    if not is_default then
      return { glyph = glyph, hl = hl }
    end
  end

  for _, extension in ipairs(spec.extensions or {}) do
    local glyph, hl, is_default = mini_icons.get("extension", extension)
    if not is_default then
      return { glyph = glyph, hl = hl }
    end
  end

  local glyph, hl, is_default = mini_icons.get("filetype", spec.id)
  if not is_default then
    return { glyph = glyph, hl = hl }
  end

  return { glyph = "󰈔", hl = "MiniIconsGrey" }
end

return {
  {
    "nvim-mini/mini.icons",
    opts = function(_, opts)
      local mini_icons = require("mini.icons")

      opts.default = opts.default or {}
      opts.directory = opts.directory or {}
      opts.extension = opts.extension or {}
      opts.file = opts.file or {}
      opts.filetype = opts.filetype or {}

      local mapped_extensions = {}
      local mapped_files = {}

      -- Eyecons uses one coherent folder treatment instead of per-folder logos.
      local folder_icon = { glyph = "", hl = "Keyword" }
      opts.default.directory = copy_icon(folder_icon)
      for _, name in ipairs(mini_icons.list("directory")) do
        opts.directory[name] = copy_icon(folder_icon)
      end

      for _, spec in ipairs(specs) do
        local icon = resolve_icon(mini_icons, spec)

        for _, extension in ipairs(spec.extensions or {}) do
          local normalized = extension:lower()
          opts.extension[normalized] = copy_icon(icon)
          mapped_extensions[normalized] = copy_icon(icon)
        end

        for _, filename in ipairs(spec.files or {}) do
          opts.file[filename] = copy_icon(icon)
          mapped_files[filename:lower()] = copy_icon(icon)
        end

        opts.filetype[spec.id] = copy_icon(icon)
        for _, filetype in ipairs(filetype_aliases[spec.id] or {}) do
          opts.filetype[filetype] = copy_icon(icon)
        end
      end

      -- MiniIcons resolves built-in special filenames before extensions. Mirror
      -- Eyecons' extension rules onto those names so init.lua still looks like
      -- every other Lua file, while explicit names such as README win first.
      local extensions_by_length = vim.tbl_keys(mapped_extensions)
      table.sort(extensions_by_length, function(a, b)
        return #a > #b
      end)

      local function icon_for_filename(filename)
        local lower = filename:lower()
        if mapped_files[lower] then
          return mapped_files[lower]
        end

        for _, extension in ipairs(extensions_by_length) do
          if lower:sub(-#extension - 1) == "." .. extension then
            return mapped_extensions[extension]
          end
        end
      end

      for filename, icon in pairs(mapped_files) do
        opts.file[filename:upper()] = copy_icon(icon)
        opts.file[filename:gsub("^%l", string.upper)] = copy_icon(icon)

        local stem, suffix = filename:match("^([^%.]+)(%..+)$")
        if stem then
          opts.file[stem:upper() .. suffix] = copy_icon(icon)
        end
      end

      for _, filename in ipairs(mini_icons.list("file")) do
        local icon = icon_for_filename(filename)
        if icon then
          opts.file[filename] = copy_icon(icon)
        end
      end

      return opts
    end,
  },
}
